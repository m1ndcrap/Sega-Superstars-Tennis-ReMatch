#define SST_VOCAB_FLAGS(T)                                                 \
  constexpr T operator|(T a, T b) { return T(uint32_t(a) | uint32_t(b)); } \
  constexpr T operator&(T a, T b) { return T(uint32_t(a) & uint32_t(b)); } \
  constexpr T operator~(T a) { return T(~uint32_t(a)); }                   \
  inline T &operator|=(T &a, T b) { return a = a | b; }                    \
  inline T &operator&=(T &a, T b) { return a = a & b; }

